export type BrandMarkVariant = 'brand' | 'white' | 'black' | 'current';

const variantClass: Record<BrandMarkVariant, string> = {
  brand: 'text-[#00A228]',
  white: 'text-white',
  black: 'text-foreground',
  current: 'text-current',
};

type BrandMarkProps = {
  className?: string;
  size?: number;
  variant?: BrandMarkVariant;
  title?: string;
  /** When true, each petal gets a data-petal index for bloom animations. */
  animatePetals?: boolean;
};

export function BrandMark({
  className,
  size = 24,
  variant = 'brand',
  title = 'Fudfarmer',
  animatePetals = false,
}: BrandMarkProps) {
  const decorative = !title;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 138 130"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={cn(variantClass[variant], className)}
      role={decorative ? 'presentation' : 'img'}
      aria-hidden={decorative || undefined}
      aria-label={decorative ? undefined : title}
    >
      {!decorative && <title>{title}</title>}
      {PETAL_PATHS.map((d, i) => (
        <path
          key={i}
          d={d}
          fill="currentColor"
          data-petal={animatePetals ? i : undefined}
          className={animatePetals ? 'brand-loader-petal' : undefined}
        />
      ))}
    </svg>
  );
}

